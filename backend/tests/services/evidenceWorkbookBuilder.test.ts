/**
 * Unit tests for workbook sheets, xlsx encoding, and package assembly, using in-memory snapshots.
 */

import { describe, expect, it } from 'vitest';
import * as XLSX from 'xlsx';
import { EVIDENCE_ERROR_CATEGORIES, EVIDENCE_MESSAGES } from '../../src/constants/evidenceMessages';
import {
  EVIDENCE_PACKAGE_INDEX_FILENAME,
  EVIDENCE_SHEET_NAMES,
  EVIDENCE_STATIC_UNAVAILABLE_REASONS,
  EVIDENCE_WORKBOOK_SHEETS,
  EVIDENCE_WORKBOOK_TYPES
} from '../../src/constants/evidenceWorkbook';
import { EvidenceRequestError } from '../../src/services/evidenceRequestError';
import { requireLedgerDetail } from '../../src/services/evidenceSheetCommon';
import {
  buildEvidencePackage,
  buildWorkbookFile,
  buildWorkbookSheets,
  encodeWorkbook,
  requiresLedgerDetail
} from '../../src/services/evidenceWorkbookBuilder';
import { attachLedgerDetail } from '../../src/services/evidenceSnapshotService';
import type { EvidenceSnapshot, EvidenceWorkbookMeta, EvidenceWorkbookType } from '../../src/types/evidenceWorkbook';
import { readStoredZip } from '../helpers/storedZip';
import { createEvidenceDatabase } from '../helpers/evidenceSqlite';
import { makeDetail, makeSnapshot, SNAPSHOT_GENERATED_AT } from '../helpers/evidenceSnapshotFactory';

const META: EvidenceWorkbookMeta = { generatedAt: SNAPSHOT_GENERATED_AT, generatedBy: 'admin@procucev.com' };
const AVAILABLE_TYPES: EvidenceWorkbookType[] = [
  'MODULE_1_EVIDENCE',
  'SAVINGS_ENGINE_EVIDENCE',
  'FINANCIAL_VALIDATION',
  'DATA_VERSION_DIFF',
  'MANAGEMENT_QUICK_SUMMARY_EVIDENCE',
  'ANALYSIS_RUN_CONTROL'
];

const cellsOf = (bytes: Uint8Array, sheet: string): unknown[][] =>
  XLSX.utils.sheet_to_json<unknown[]>(XLSX.read(bytes, { type: 'array' }).Sheets[sheet], { header: 1 });

describe('buildWorkbookSheets', () => {
  it.each(AVAILABLE_TYPES)('produces exactly the declared sheet list for %s', (type) => {
    const sheets = buildWorkbookSheets(type, makeSnapshot(), META);
    expect(sheets.map((sheet) => sheet.name)).toEqual([...EVIDENCE_WORKBOOK_SHEETS[type]]);
    expect(sheets.every((sheet) => sheet.rows.length > 0)).toBe(true);
  });

  it('writes the README with job, version, run, generator, and cap metadata', () => {
    const [readme] = buildWorkbookSheets('SAVINGS_ENGINE_EVIDENCE', makeSnapshot({ detail: null }), META);
    const labels = readme.rows.map((row) => row[0]);
    expect(labels).toContain('Job ID');
    expect(labels).not.toContain('Transaction rows shown');
    expect(readme.rows.find((row) => row[0] === 'Generated by')?.[1]).toBe('admin@procucev.com');
  });

  it('adds transaction counts and the sheet cap to the README when ledger detail is loaded', () => {
    const [readme] = buildWorkbookSheets('MODULE_1_EVIDENCE', makeSnapshot(), META);
    expect(readme.rows.find((row) => row[0] === 'Transaction rows shown')?.[1]).toBe('2 of 4');
    expect(readme.rows.find((row) => row[0] === 'Transaction sheet cap')?.[1]).toBe(5000);
  });

  it('shows not-recorded placeholders in the README when no version or run is active', () => {
    const [readme] = buildWorkbookSheets('ANALYSIS_RUN_CONTROL', makeSnapshot({ activeVersion: null, activeRun: null }), META);
    expect(readme.rows.find((row) => row[0] === 'Active data version')?.[1]).toBe('Not recorded');
    expect(readme.rows.find((row) => row[0] === 'Active analysis run')?.[1]).toBe('Not recorded');
  });

  it('writes the ledger spend sheets from the detail with shares of the ledger total', () => {
    const sheets = buildWorkbookSheets('MODULE_1_EVIDENCE', makeSnapshot(), META);
    const supplier = sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.SUPPLIER_SPEND);
    expect(supplier?.rows[1]).toEqual(['Alpha Chem', 2, 4, 53.333333]);
    const transactions = sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.TRANSACTIONS);
    expect(transactions?.rows[1][0]).toBe('TX-1');
    expect(transactions?.rows[2][1]).toBe('');
  });

  it('writes zero shares when the ledger total is zero', () => {
    const snapshot = makeSnapshot({ ledger: { rowCount: 4, totalCr: 0 } });
    const supplier = buildWorkbookSheets('MODULE_1_EVIDENCE', snapshot, META).find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.SUPPLIER_SPEND);
    expect(supplier?.rows[1][3]).toBe(0);
  });

  it('fails loudly when MODULE_1 is built without ledger detail', () => {
    expect(() => buildWorkbookSheets('MODULE_1_EVIDENCE', makeSnapshot({ detail: null }), META)).toThrow(
      'Ledger detail was not loaded for job AIC-TEST'
    );
    expect(() => requireLedgerDetail(makeSnapshot({ detail: null }))).toThrow('Ledger detail');
    expect(requireLedgerDetail(makeSnapshot()).sampleLimit).toBe(5000);
  });

  it('writes the savings bridge with status and formula for each component', () => {
    const sheets = buildWorkbookSheets('SAVINGS_ENGINE_EVIDENCE', makeSnapshot(), META);
    const bridge = sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.CALCULATION_BRIDGE);
    expect(bridge?.rows[3]).toEqual([3, 'Net defensible opportunity', 2, 2, 'PASS', 'Gross - Overlap = Net defensible']);
  });

  it('marks bridge rows FAIL when a source value is missing', () => {
    const snapshot = makeSnapshot({ activeRun: null });
    const bridge = buildWorkbookSheets('SAVINGS_ENGINE_EVIDENCE', snapshot, META).find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.CALCULATION_BRIDGE);
    expect(bridge?.rows[1][4]).toBe('FAIL');
  });

  it('writes validation rows for the ledger count and every parity check', () => {
    const sheets = buildWorkbookSheets('FINANCIAL_VALIDATION', makeSnapshot(), META);
    const validation = sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.VALIDATION_CHECKS);
    expect(validation?.rows[1]).toEqual(['Ledger rows in scope', 'greater than 0', 4, 0, 'PASS', 'Rows with this assessment_id and tenant_id']);
    expect(validation?.rows).toHaveLength(6);
    const emptyLedger = buildWorkbookSheets('FINANCIAL_VALIDATION', makeSnapshot({ ledger: { rowCount: 0, totalCr: 0 } }), META);
    expect(emptyLedger.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.VALIDATION_CHECKS)?.rows[1][4]).toBe('FAIL');
  });

  it('lists every data version and a diff row per consecutive pair', () => {
    const sheets = buildWorkbookSheets('DATA_VERSION_DIFF', makeSnapshot(), META);
    const versions = sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.DATA_VERSIONS);
    expect(versions?.rows).toHaveLength(3);
    const diff = sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.VERSION_DIFF);
    expect(diff?.rows[1]).toEqual(['DV-1', 'DV-2', 4, 5, 1, 'Yes', 'Yes']);
  });

  it('reports no prior version when only one data version exists or record counts are unknown', () => {
    const single = makeSnapshot({ versions: [makeVersionFor('DV-2')] });
    const diffSingle = buildWorkbookSheets('DATA_VERSION_DIFF', single, META).find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.VERSION_DIFF);
    expect(diffSingle?.rows[1]).toEqual(['No prior version to compare']);

    const unknownCounts = makeSnapshot({
      versions: [makeVersionFor('DV-1', { recordCount: null, fileName: 'same.xlsx', checksum: 'x' }), makeVersionFor('DV-2', { versionNumber: 2, recordCount: null, fileName: 'same.xlsx', checksum: 'x' })]
    });
    const diffUnknown = buildWorkbookSheets('DATA_VERSION_DIFF', unknownCounts, META).find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.VERSION_DIFF);
    expect(diffUnknown?.rows[1]).toEqual(['DV-1', 'DV-2', '', '', '', 'No', 'No']);
  });

  it('lists analysis runs with gates, approval, supersession, and totals', () => {
    const runs = buildWorkbookSheets('ANALYSIS_RUN_CONTROL', makeSnapshot(), META).find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.ANALYSIS_RUNS);
    expect(runs?.rows[1]).toEqual(['RUN-1', 'DV-2', 'COMPLETED', 7.5, 7.5, 3, 1, 2, 2, 26.6667, 'Yes', 'Yes', 'No', '2026-02-01T00:00:00Z']);
  });

  it('builds the KPI reconciliation and the parity sheet from the same checks', () => {
    const sheets = buildWorkbookSheets('MANAGEMENT_QUICK_SUMMARY_EVIDENCE', makeSnapshot(), META);
    expect(sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.KPI_RECONCILIATION)?.rows).toHaveLength(5);
    const parity = sheets.find((sheet) => sheet.name === EVIDENCE_SHEET_NAMES.PARITY);
    expect(parity?.rows[0]).toContain('Supporting Sheet');
    expect(parity?.rows).toHaveLength(5);
  });

  it('builds the declared sheets even for unavailable types, using an empty type sheet list', () => {
    const sheets = buildWorkbookSheets('REPORT_EVIDENCE', makeSnapshot(), META);
    expect(sheets.map((sheet) => sheet.name)).toEqual([EVIDENCE_SHEET_NAMES.README, EVIDENCE_SHEET_NAMES.SUMMARY, EVIDENCE_SHEET_NAMES.PARITY]);
  });
});

describe('workbook files and packages', () => {
  it('encodes an xlsx whose sheets match the sheet list and can be read back', () => {
    const bytes = encodeWorkbook(buildWorkbookSheets('MODULE_1_EVIDENCE', makeSnapshot(), META));
    expect(bytes[0]).toBe(0x50);
    expect(XLSX.read(bytes, { type: 'array' }).SheetNames).toEqual([...EVIDENCE_WORKBOOK_SHEETS.MODULE_1_EVIDENCE]);
    expect(cellsOf(bytes, EVIDENCE_SHEET_NAMES.SUPPLIER_SPEND)[1][0]).toBe('Alpha Chem');
  });

  it('builds a workbook file with its filename and sheet count', () => {
    const file = buildWorkbookFile('ANALYSIS_RUN_CONTROL', makeSnapshot(), META);
    expect(file).toMatchObject({ type: 'ANALYSIS_RUN_CONTROL', filename: '09_Analysis_Run_Control.xlsx', sheetCount: 4 });
  });

  it('refuses to build an unavailable workbook with a 409 that carries the reason', () => {
    const snapshot = makeSnapshot({ ledger: { rowCount: 0, totalCr: 0 } });
    try {
      buildWorkbookFile('MODULE_1_EVIDENCE', snapshot, META);
      throw new Error('expected a 409');
    } catch (error) {
      expect(error).toBeInstanceOf(EvidenceRequestError);
      expect(error).toMatchObject({ status: 409, category: EVIDENCE_ERROR_CATEGORIES.CONFLICT });
      expect((error as EvidenceRequestError).message).toBe(EVIDENCE_MESSAGES.workbookUnavailable('AIC-TEST', EVIDENCE_MESSAGES.ledgerEmpty('AIC-TEST')));
    }
  });

  it('assembles a package of available workbooks plus a readable index with exclusions', () => {
    const pack = buildEvidencePackage(makeSnapshot(), META);
    expect(pack).toMatchObject({ filename: 'Complete_Analysis_Evidence_Package_AIC-TEST.zip', includedCount: 6, excludedCount: 10 });
    const entries = readStoredZip(pack.bytes);
    expect(entries.map((entry) => entry.name)).toContain(EVIDENCE_PACKAGE_INDEX_FILENAME);
    const index = new TextDecoder().decode(entries[entries.length - 1].data);
    expect(index).toContain('Workbooks not included:');
    expect(index).toContain(`02_Module_2_Evidence.xlsx: ${EVIDENCE_STATIC_UNAVAILABLE_REASONS.MODULE_2_EVIDENCE}`);
  });

  it('refuses an empty package with a 409', () => {
    const snapshot = makeSnapshot({ ledger: { rowCount: 0, totalCr: 0 }, runs: [], activeRun: null, versions: [], activeVersion: null });
    expect(() => buildEvidencePackage(snapshot, META)).toThrow(EVIDENCE_MESSAGES.packageEmpty('AIC-TEST'));
  });

  it('decides when ledger detail must be loaded', () => {
    expect(requiresLedgerDetail('MODULE_1_EVIDENCE', makeSnapshot())).toBe(true);
    expect(requiresLedgerDetail('MODULE_1_EVIDENCE', makeSnapshot({ ledger: { rowCount: 0, totalCr: 0 } }))).toBe(false);
    expect(requiresLedgerDetail('FINANCIAL_VALIDATION', makeSnapshot())).toBe(false);
  });

  it('builds every primary type without throwing when its data is present', () => {
    const snapshot: EvidenceSnapshot = makeSnapshot({ detail: makeDetail() });
    for (const type of EVIDENCE_WORKBOOK_TYPES) {
      const available = AVAILABLE_TYPES.includes(type);
      if (available) {
        expect(buildWorkbookFile(type, snapshot, META).sheetCount).toBe(EVIDENCE_WORKBOOK_SHEETS[type].length);
      } else {
        expect(() => buildWorkbookFile(type, snapshot, META)).toThrow(EvidenceRequestError);
      }
    }
  });
});

describe('ledger detail attachment', () => {
  it('loads ledger detail once and reuses an attached copy', async () => {
    const fixture = createEvidenceDatabase();
    try {
      const snapshot = makeSnapshot({ tenantId: 'TNT-TEST', jobId: 'AIC-A', detail: null });
      const attached = await attachLedgerDetail(fixture.d1, snapshot, 'req-attach');
      expect(attached.detail?.suppliers[0]).toEqual({ groupKey: 'Alpha Chem', rowCount: 2, totalCr: 4 });
      expect(attached.detail?.sample).toHaveLength(4);
      const reused = await attachLedgerDetail(fixture.d1, attached, 'req-attach');
      expect(reused).toBe(attached);
    } finally {
      fixture.close();
    }
  });
});

const makeVersionFor = (
  dataVersionId: string,
  overrides: Partial<EvidenceSnapshot['versions'][number]> = {}
): EvidenceSnapshot['versions'][number] => ({
  dataVersionId,
  versionNumber: dataVersionId === 'DV-1' ? 1 : 2,
  fileName: dataVersionId === 'DV-1' ? 'alpha-v1.xlsx' : 'alpha-v2.xlsx',
  fileSize: 1000,
  checksum: dataVersionId,
  uploadedBy: 'analyst@procucev.com',
  uploadedAt: '2026-01-01T00:00:00Z',
  recordCount: dataVersionId === 'DV-1' ? 4 : 5,
  isSuperseded: false,
  ...overrides
});
